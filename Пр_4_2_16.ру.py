# Даны положительные числа A и B (A > B). На отрезке длины A размещено
# максимально возможное количество отрезков длины B (без наложений).
# Не используя умножение и деление, найти количество отрезков B.

while True:
    try:
        a = float(input("Введите длину отрезка A: "))
        b = float(input("Введите длину отрезка B: "))
        if a > 0 and b > 0 and a > b:
            break  # Ввод правильный, выходим из цикла
        print("Ошибка: числа должны быть положительными и A > B.")
    except ValueError:
        print("Ошибка: Введите число.")

k = 0  # Количество отрезков B

while a >= b:
    a = round(a - b, 10)  # round убирает погрешность вещественных чисел
    k += 1

print("Количество отрезков B на отрезке A:", k)