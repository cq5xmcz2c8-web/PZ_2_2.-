# Дан список A размера N и целое число K (1 < K < 4, K < N).
# Осуществить циклический сдвиг элементов списка вправо на K позиций
# (A1 перейдет в AK+1, A2 - в AK+2, ..., AN - в AK).
# Допускается использовать вспомогательный список из 4 элементов.
import random

n = input("Введите размер списка N (N >= 3): ")
while type(n) != int or n < 3:  # Обработка исключений
    try:
        n = int(n)
        if n < 3:
            print("Размер должен быть не меньше 3")
            n = input("Введите размер списка N (N >= 3): ")
    except ValueError:
        print("Число введено неправильно")
        n = input("Введите размер списка N (N >= 3): ")

k = input("Введите число K (1 < K < 4, K < N): ")
while type(k) != int or k < 2 or k > 3 or k >= n:  # Обработка исключений
    try:
        k = int(k)
        if k < 2 or k > 3 or k >= n:
            print("K должно быть 2 или 3 и меньше N")
            k = input("Введите число K (1 < K < 4, K < N): ")
    except ValueError:
        print("Число введено неправильно")
        k = input("Введите число K (1 < K < 4, K < N): ")

a = []
for i in range(n):
    a.append(random.randint(1, 100))
print("Исходный список:", a)

tmp = a[n - k:]  # Вспомогательный список: последние K элементов
for i in range(n - 1, k - 1, -1):  # Сдвигаем остальные элементы вправо
    a[i] = a[i - k]
for i in range(k):  # Последние элементы ставим в начало
    a[i] = tmp[i]

print("Результирующий список:", a)