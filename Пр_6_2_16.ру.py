# Дан целочисленный список размера N, содержащий ровно два одинаковых
# элемента. Найти номера одинаковых элементов и вывести их по возрастанию.
import random

n = input("Введите размер списка N (N >= 2): ")
while type(n) != int or n < 2:  # Обработка исключений
    try:
        n = int(n)
        if n < 2:
            print("Размер должен быть не меньше 2")
            n = input("Введите размер списка N (N >= 2): ")
    except ValueError:
        print("Число введено неправильно")
        n = input("Введите размер списка N (N >= 2): ")

# Берем N - 1 разных чисел и добавляем одно повторяющееся
a = random.sample(range(1, 1000), n - 1)
a.append(random.choice(a))
random.shuffle(a)
print("Исходный список:", a)

# Ищем два одинаковых элемента (номера считаем с 1)
for i in range(n):
    for j in range(i + 1, n):
        if a[i] == a[j]:
            print("Номера одинаковых элементов:", i + 1, j + 1)