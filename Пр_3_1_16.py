# Даны три целых числа A, B, C.
# Проверить, ровно два из них являются положительными.

while True:
    try:
        a = int(input("Введите первое число: "))
        b = int(input("Введите второе число: "))
        c = int(input("Введите третье число: "))

        k = 0  # Счетчик положительных чисел

        if a > 0:
            k += 1
        if b > 0:
            k += 1
        if c > 0:
            k += 1

        # Проверяем, равно ли количество положительных чисел двум
        if k == 2:
            print("ровно два числа являются положительными")
        else:
            print("положительных чисел не два, а", k)
        break  # Завершаем цикл

    except ValueError:
        print("Ошибка: Введите целое число.")