# Даны три целых числа A, B, C.
# Проверить, ровно два из них являются положительными.

a, b, c = input("Введите первое число: "), input("Введите второе число: "), input("Введите третье число: ")

while type(a) != int:  # Проверка первого числа
    try:
        a = int(a)
    except ValueError:
        print("Неправильно ввели!")
        a = input("Введите первое число: ")

while type(b) != int:  # Проверка второго числа
    try:
        b = int(b)
    except ValueError:
        print("Неправильно ввели!")
        b = input("Введите второе число: ")

while type(c) != int:  # Проверка третьего числа
    try:
        c = int(c)
    except ValueError:
        print("Неправильно ввели!")
        c = input("Введите третье число: ")

k = 0  # Счетчик положительных чисел

if a > 0:
    k += 1
if b > 0:
    k += 1
if c > 0:
    k += 1

# Проверяем, равно ли количество положительных чисел двум
print("Ровно два числа являются положительными:", k == 2)