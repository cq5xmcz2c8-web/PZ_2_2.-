# Даны три целых числа, одно из которых отлично от двух других,
# равных между собой. Определить порядковый номер числа,
# отличного от остальных.

while True:
    try:
        a = int(input("Введите первое число: "))
        b = int(input("Введите второе число: "))
        c = int(input("Введите третье число: "))
        break  # Ввод правильный, выходим из цикла
    except ValueError:
        print("Ошибка: Введите целое число.")

# Определяем, какое число отличается от двух других
if a == b:
    print("Отличается третье число (номер 3)")
elif a == c:
    print("Отличается второе число (номер 2)")
else:
    print("Отличается первое число (номер 1)")