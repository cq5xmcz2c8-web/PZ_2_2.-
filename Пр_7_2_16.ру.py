# Дана строка-предложение на русском языке. Преобразовать строку так, чтобы
# каждое слово начиналось с заглавной буквы. Словом считать набор символов,
# не содержащий пробелов. Слова, не начинающиеся с буквы, не изменять.

s = input("Введите предложение: ")
while s == "":  # Обработка исключений
    print("Строка пустая, повторите ввод")
    s = input("Введите предложение: ")

words = s.split(" ")  # Делим по одному пробелу, чтобы сохранить все пробелы
for i in range(len(words)):
    # Пустой элемент получается при нескольких пробелах подряд
    if words[i] != "" and words[i][0].isalpha():
        words[i] = words[i][0].upper() + words[i][1:]

result = " ".join(words)

print("Исходная строка:", s)
print("Результирующая строка:", result)