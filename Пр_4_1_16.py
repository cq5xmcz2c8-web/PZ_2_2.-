# Дано вещественное число A и целое число N (N > 0).
# Используя один цикл, найти значение выражения
# 1 - A + A^2 - A^3 + ... + (-1)^N * A^N.
# Условный оператор в вычислениях не использовать.

while True:
    try:
        a = float(input("Введите вещественное число A: "))
        n = int(input("Введите целое число N (N > 0): "))
        if n > 0:
            break  # Ввод правильный, выходим из цикла
        print("Ошибка: N должно быть больше 0.")
    except ValueError:
        print("Ошибка: Введите число.")

s = 0  # Сумма выражения
term = 1  # Текущее слагаемое (начинаем с A^0 = 1)

for i in range(n + 1):
    s += term
    term *= -a  # Следующее слагаемое с противоположным знаком

print("Значение выражения:", s)



